export const createInitialCartItem = (product: Product, quantity = 1, discountPerItem = 10000): CartItem => {
  const actualPrice = Math.max(0, product.basePrice - discountPerItem);
  return {
    id: product.id,
    product,
    unit: product.baseUnit,
    quantity,
    unitPrice: product.basePrice,
    discountPerItem,
    discountType: 'vnd',
    actualPrice,
    totalAmount: actualPrice * quantity,
    isBelowCostApproved: false,
  };
};

