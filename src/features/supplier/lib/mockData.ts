export function computeStats(suppliers: SupplierSummary[]): SupplierStats {
  const activeSuppliers = suppliers.filter(s => s.status === 'Active');
  const totalDebt = activeSuppliers.reduce((sum, s) => sum + s.currentDebt, 0);
  const overdueDebt = activeSuppliers.reduce((sum, s) => sum + s.overdueDebt, 0);
  const dueSoon7Days = activeSuppliers
    .filter(s => s.currentDebt > 0 && s.overdueDebt === 0 && s.paymentTermDays <= 7)
    .reduce((sum, s) => sum + s.currentDebt, 0);

  return {
    totalDebt,
    overdueDebt,
    dueSoon7Days,
    totalActive: activeSuppliers.length
  };
}

